def step_tables(a):
    W, X = load_C()
    with open(os.path.join(RESULTS, "baseline_C.json")) as f:
        base = {(r["format"], r["policy"]): r for r in json.load(f)}
    with open(os.path.join(RESULTS, "baseline_C_wx.json")) as f:
        base_wx = {(r["format"], r["policy"]): r for r in json.load(f)}
    out = []
    pols = ["ocp", "ceil", "opt", "opt_out"]

    # T1 main table: primary metric = held-out Y error (D6); class rule next to optimised (D5)
    rows = []
    for n in sorted(CANDIDATES, key=lambda n: base[n, "ocp"]["y_rel_err_heldout"]):
        rows.append([n] + [pct(base[n, p]["y_rel_err_heldout"]) for p in pols]
                    + [pct(base[n, "ocp"]["y_rel_err"]), pct(base[n, "opt"]["y_rel_err"]),
                       pct(base[n, "ocp"]["w_rel_err"]), base[n, "ocp"]["bits_per_elem"]])
    out.append(write_table(
        "T1_main_C", ["format"] + [f"held-out Y err % ({p})" for p in pols]
        + ["all-X Y err % (ocp)", "all-X Y err % (opt)", "W err % (ocp)", "bits/elem"], rows,
        "Dataset C, weights only (X stays FP32). Primary metric: relative Frobenius error of Y = W X on the "
        "held-out odd columns of X_cal (opt_out fits H on the even columns only). 'ocp' is the class floor "
        "rule; 'opt' searches the shared exponent e_ocp + {-2..+1} per block. Sorted by the class rule."))

    # T2 storage (D11)
    rows = []
    for n in ALL:
        lay = layout(n)
        blk = lay["block"]
        nb = len(blocks(100, blk))
        rows.append([n, "candidate" if n in FORMATS else "variant", str(blk), nb, lay["scale_bits"],
                     f"{lay['field'][0]}..{lay['field'][1]}", format_storage(n, 100, 100)[0],
                     round(format_storage(n, 100, 100)[1], 4)])
    out.append(write_table(
        "T2_storage", ["format", "role", "block", "blocks/row (K=100)", "exp bits", "exp field range",
                       "total bits (100x100)", "bits/elem"], rows,
        "True storage per element for a 100x100 matrix, counting each row's tail block with its own "
        "shared exponent (D11). Elements are 6 bits."))

    # T3 E4M1 conventions (D3)
    rows = []
    desc = {"MXFP6_E4M1": "no reserved code, vmax 384 (our choice)",
            "MXFP6_E4M1_nan1": "one NaN code (E4M3-style), vmax 256",
            "MXFP6_E4M1_v192": "top exponent reserved (IEEE-like), vmax 192"}
    for n, d in desc.items():
        rows.append([n, d] + [pct(base[n, p]["y_rel_err_heldout"]) for p in ("ocp", "ceil", "opt")]
                    + [base[n, "ocp"]["n_range"], base[n, "ocp"]["n_saturated"]])
    out.append(write_table(
        "T3_e4m1_conventions", ["variant", "convention", "held-out Y err % (ocp)", "(ceil)", "(opt)",
                                "range count (ocp)", "saturated count (ocp)"], rows,
        "E4M1 under three top-code conventions, dataset C. E2M3 (the winner) is "
        f"{pct(base['MXFP6_E2M3', 'ocp']['y_rel_err_heldout']):.3f}% under ocp, so E4M1 loses under every convention."))

    # T4 BFP family and ablation (D1)
    rows = []
    for n, d in [("BFP6", "16|4|5 floor, RNE (candidate)"), ("BFP6_g32e8", "32|8|5 floor, RNE (= MXINT6)"),
                 ("BFP6_b32_ceil", "32|8|5 ceil, RNE (v1 BFP6)"), ("BFP6_row", "100|8|5 ceil, RNE (one block per row)"),
                 ("MXINT6", "reference: MXINT6")]:
        rows.append([n, d, format_storage(n, 100, 100)[1]]
                    + [pct(base[n, p]["y_rel_err_heldout"]) for p in ("ocp", "ceil", "opt")])
    for g, eb in ((16, 4), (32, 8)):
        for rule in ("floor", "floor+1"):
            for rnd in ("rne", "trunc"):
                Wq = bfp_ablation(W, g, rule, rnd, eb)
                rows.append([f"ablation g={g}", f"{g}|{eb}|5 exp {rule}, {rnd}", 6 + eb * len(blocks(100, g)) / 100,
                             yerr_heldout(W, X, Wq), "", ""])
    out.append(write_table(
        "T4_bfp_family", ["format", "definition g|e|m, exponent rule, rounding", "bits/elem",
                          "held-out Y err % (ocp)", "(ceil)", "(opt)"], rows,
        "BFP family on dataset C. BFP 32|8|5 with the floor rule is numerically identical to MXINT6 "
        "(test_v2_bfp_32_8_5_identical_to_mxint6). Ablation rows are not candidates: they show that "
        "truncation or an always-higher exponent is much worse than floor + RNE."))

    # T5 W only vs W+X (D2)
    rows = []
    for n in sorted(CANDIDATES, key=lambda n: base[n, "ocp"]["y_rel_err_heldout"]):
        rows.append([n, pct(base[n, "ocp"]["y_rel_err_heldout"]), pct(base_wx[n, "ocp"]["y_rel_err_heldout"]),
                     pct(base[n, "opt"]["y_rel_err_heldout"]), pct(base_wx[n, "opt"]["y_rel_err_heldout"]),
                     pct(base_wx[n, "ocp"]["x_rel_err"])])
    out.append(write_table(
        "T5_w_vs_wx", ["format", "W only (ocp)", "W+X (ocp)", "W only (opt)", "W+X (opt)", "X err % (ocp)"], rows,
        "Held-out Y error (%), dataset C. W+X quantizes X with the same format, blocks down the columns of X "
        "(its reduction axis)."))

    # T6 class diagnostics under ocp (Lecture 19 definitions)
    rows = [[n, base[n, "ocp"]["n_range"], base[n, "ocp"]["n_saturated"], base[n, "ocp"]["n_zeroed"],
             base[n, "ocp"]["n_subnormal"], base[n, "ocp"]["n_scale_clamped"]] for n in ALL]
    out.append(write_table(
        "T6_diagnostics_ocp", ["format", "range (before rounding)", "saturated (after rounding)", "zeroed",
                               "subnormal", "clamped blocks"], rows,
        "Element counts on W_C (10,000 weights) under the class rule. Definitions follow the Lecture 19 notebook: "
        "'range' = |w|/scale > vmax before rounding; 'saturated' = the rounded value exceeds vmax."))

    # T7 / T8: datasets A-E as context (only if the course npz is available)
    npz = find_npz(a.npz)
    if npz:
        with np.load(npz) as d:
            XA = d["X_cal"].astype(np.float64)
            Ws = {k: d["W_" + k].astype(np.float64) for k in "ABCDE"}
        rows, rows_tc = [], []
        for k in tqdm(list(Ws), desc="datasets A-E", leave=False):
            Wk = Ws[k]
            res = {(n, p): yerr_heldout(Wk, XA, quantize(Wk, n, policy=p)[0]) for n in CANDIDATES for p in ("ocp", "opt")}
            for p in ("ocp", "opt"):
                order = sorted(CANDIDATES, key=lambda n: res[n, p])
                rows.append([k, p] + [res[n, p] for n in CANDIDATES] + [order[0], res[order[1], p] - res[order[0], p]])
            for p in ("ocp", "opt"):
                s = yerr_heldout(Wk, XA, quantize(Wk, "MXINT6", policy=p)[0])
                t = yerr_heldout(Wk, XA, quantize(Wk, "MXINT6_tc", policy=p)[0])
                rows_tc.append([k, p, s, t, t - s])
        out.append(write_table(
            "T7_datasets_A_to_E", ["dataset", "policy"] + CANDIDATES + ["winner", "margin to 2nd (pp)"], rows,
            "Held-out Y error (%) for all five datasets, weights only. Context for Q3 only; our assignment is C."))
        out.append(write_table(
            "T8_mxint6_sym_vs_tc", ["dataset", "policy", "symmetric [-31,31]", "two's compl. [-32,31]", "difference (pp)"],
            rows_tc, "MXINT6 integer range convention (D10), held-out Y error (%)."))
    else:
        W, X = load_C()
        rows_tc = [["C", p, yerr_heldout(W, X, quantize(W, "MXINT6", policy=p)[0]),
                    yerr_heldout(W, X, quantize(W, "MXINT6_tc", policy=p)[0])] for p in ("ocp", "opt")]
        rows_tc = [r + [r[3] - r[2]] for r in rows_tc]
        out.append(write_table(
            "T8_mxint6_sym_vs_tc", ["dataset", "policy", "symmetric [-31,31]", "two's compl. [-32,31]", "difference (pp)"],
            rows_tc, "MXINT6 integer range convention (D10), held-out Y error (%). Datasets A-E: pass --npz."))
        print("  (datasets A-E skipped: pass --npz path/to/assignment_data.npz or put it in data/)")
    return out


def step_scripts(a):
    outs = []
    todo = CORE_SCRIPTS + [s for s in OPTIONAL_SCRIPTS if os.path.exists(os.path.join(HERE, s))]
    failed = []
    for s in tqdm(todo, desc="team scripts", leave=False):
        log = os.path.join(LOGS, s.replace(".py", ".txt"))
        code, _ = run([s], log)
        outs.append(log)
        if code:
            failed.append(s)
    if failed:
        print(f"  WARNING: these scripts exited with an error (see results/logs/): {failed}")
        for s in failed:
            with open(os.path.join(LOGS, s.replace(".py", ".txt"))) as f:
                last = [l for l in f.read().strip().splitlines() if l.strip()][-1]
            print(f"    {s}: {last}")
            if "No module named" in last:
                print(f"    -> install it:  python -m pip install {last.split(chr(39))[1]}")
        print("  This step is NOT checkpointed, so the next run retries it.")
    return outs, not failed


def step_manifest(a):
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=HERE, capture_output=True,
                                text=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain"], cwd=HERE, capture_output=True,
                               text=True).stdout.strip()
    except OSError:
        commit, dirty = "unknown", ""
    files = []
    for d in (RESULTS, os.path.join(HERE, "figures")):
        for root, _, fs in os.walk(d):
            for f in sorted(fs):
                if f.endswith(".ckpt.jsonl") or f == "run_all_state.json":
                    continue
                p = os.path.join(root, f)
                files.append(f"- `{os.path.relpath(p, HERE)}`  sha1 {sha([p])}")
    data = [f"- `{f}`  sha1 {sha([os.path.join(DATA, f)])}" for f in sorted(os.listdir(DATA)) if f.endswith((".npy", ".npz"))]
    text = [
        "# Run manifest (generated by run_all.py)", "",
        f"- date: {time.strftime('%Y-%m-%d %H:%M:%S')}",
        f"- git commit: {commit}{' (with uncommitted changes)' if dirty else ''}",
        f"- python {platform.python_version()}, numpy {np.__version__}, {platform.platform()}",
        "- seeds: fixed inside each script; PYTHONHASHSEED=0", "", "## Data", *data, "", "## Outputs", *files, "",
    ]
    p = os.path.join(RESULTS, "RUN_MANIFEST.md")
    with open(p, "w") as f:
        f.write("\n".join(text))
    return [p]


STEPS = [
    ("tests", step_tests, ["test_formats.py", "formats.py"]),
    ("baseline", step_baseline, ["run_baseline.py", "formats.py"]),
    ("baseline_wx", step_baseline_wx, ["run_baseline.py", "formats.py"]),
    ("tables", step_tables, ["run_all.py", "formats.py"]),
    ("scripts", step_scripts, CORE_SCRIPTS + OPTIONAL_SCRIPTS + ["formats.py", "predictor.py", "data.py"]),
    ("manifest", step_manifest, None),          # always rerun
]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--fresh", action="store_true", help="ignore results/run_all_state.json")
    ap.add_argument("--npz", default=None, help="course assignment_data.npz (datasets A-E)")
    ap.add_argument("--only", choices=[s[0] for s in STEPS], help="run a single step")
    a = ap.parse_args()
    os.makedirs(LOGS, exist_ok=True)

    state = {}
    if os.path.exists(STATE) and not a.fresh:
        with open(STATE) as f:
            state = json.load(f)
    data_files = [os.path.join(DATA, f) for f in ("W_C.npy", "X_cal.npy")]
    npz = find_npz(a.npz)
    t_all = time.perf_counter()
    for name, fn, deps in tqdm(STEPS, desc="run_all"):
        if a.only and name != a.only:
            continue
        fp = None if deps is None else sha([os.path.join(HERE, d) for d in deps] + data_files
                                           + ([npz.encode()] if npz and name == "tables" else []))
        prev = state.get(name)
        if fp and prev and prev["fingerprint"] == fp and all(os.path.exists(o) for o in prev["outputs"]):
            print(f"\n[{name}] unchanged since last run, skipped (use --fresh to force)")
            continue
        t0 = time.perf_counter()
        print(f"\n[{name}]")
        res = fn(a)
        outs, ok = res if isinstance(res, tuple) else (res, True)
        for o in outs:
            print(f"  -> {os.path.relpath(o, HERE)}")
        if not ok:                                      # a failed step is retried on the next run
            state.pop(name, None)
            continue
        state[name] = dict(fingerprint=fp, outputs=outs, seconds=round(time.perf_counter() - t0, 2))
        with open(STATE, "w") as f:                     # checkpoint after every step
            json.dump(state, f, indent=1)
    print(f"\nDone in {time.perf_counter() - t_all:.1f} s. Tables: results/tables/, figures: figures/, "
          f"logs: results/logs/, manifest: results/RUN_MANIFEST.md")


if __name__ == "__main__":
    main()
