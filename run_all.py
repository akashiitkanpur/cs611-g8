# --------------------------------------------------------------------------- helpers
def sha(paths_or_bytes):
    h = hashlib.sha1()
    for x in paths_or_bytes:
        if isinstance(x, bytes):
            h.update(x)
        elif os.path.exists(x):
            with open(x, "rb") as f:
                h.update(f.read())
        else:
            h.update(f"missing:{x}".encode())
    return h.hexdigest()[:16]


def run(cmd, log=None):
    env = {**os.environ, "PYTHONHASHSEED": "0", "MPLBACKEND": "Agg"}
    t0 = time.perf_counter()
    p = subprocess.run([sys.executable] + cmd, cwd=HERE, env=env, capture_output=True, text=True)
    out = p.stdout + (("\n[stderr]\n" + p.stderr) if p.stderr.strip() else "")
    if log:
        os.makedirs(os.path.dirname(log), exist_ok=True)
        with open(log, "w") as f:
            f.write(f"$ python {' '.join(cmd)}\n# exit {p.returncode}, {time.perf_counter() - t0:.1f} s\n\n{out}")
    return p.returncode, out


def write_table(name, header, rows, note=""):
    """results/tables/<name>.md (readable) and .csv (exact numbers)."""
    os.makedirs(TABLES, exist_ok=True)
    with open(os.path.join(TABLES, name + ".csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    fmt = lambda v: f"{v:.3f}" if isinstance(v, float) else str(v).replace("|", "\\|")   # noqa: E731
    lines = ["| " + " | ".join(fmt(h) for h in header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
    with open(os.path.join(TABLES, name + ".md"), "w") as f:
        f.write(f"<!-- generated by run_all.py; do not edit by hand -->\n{note.strip()}\n\n" + "\n".join(lines) + "\n")
    return os.path.join(TABLES, name + ".md")


