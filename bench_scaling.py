"""Cost of selection vs matrix size (Aryan).   python bench_scaling.py [--max 4096]

LLM-like weights (Student-t4 * 0.02, 1% of input channels x10) with channel-gain activations.
For each size: time to select with brute force (quantize all five, diag-H error), the exact
sketch (one format-independent pass), and the importance-sampled certified selector (block
maxima + a sample); whether they agree; how many blocks the sampler rounded.  Writes
results/selector_scaling.md.
"""
import argparse
import os
import time

import numpy as np

import selector as S

HERE = os.path.dirname(os.path.abspath(__file__))


def make(n, rng):
    W = 0.02 * rng.standard_t(4, (n, n))
    cols = rng.choice(n, max(1, n // 100), replace=False)
    W[:, cols] *= 10
    h = np.exp(rng.normal(0, 1, n)) * 256          # H_jj of 256 calibration tokens
    return W, h


def timed(fn, *a, **k):
    t = time.perf_counter()
    out = fn(*a, **k)
    return out, time.perf_counter() - t


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--max", type=int, default=4096)
    a = ap.parse_args()
    rng = np.random.default_rng(5)
    rows = []
    n = 128
    while n <= a.max:
        W, h = make(n, rng)
        ex, te = timed(S.exhaustive, W, h)
        sk, ts = timed(S.sketch_select, W, h)
        ce, tc = timed(S.certified_is, W, h)
        used, tot, ok = S.certified_is.last
        pe, ps, pc = (min(d, key=d.get) for d in (ex, sk, ce))
        srt = sorted(ex.values())
        rows.append((n, n * n, te, ts, tc, used, tot, ok, pe, ps == pe, pc == pe, 10 * np.log10(srt[1] / srt[0])))
        print(f"  {n}x{n}: brute {te:.3f}s sketch {ts:.3f}s certified {tc:.3f}s ({used}/{tot} blocks)  {pe}")
        n *= 2
    md = ["<!-- generated by bench_scaling.py; do not edit by hand -->",
          "Selection cost vs matrix size. LLM-like W (Student-t4 x 0.02, 1% of input channels x10), "
          "channel-gain activations (H_jj log-normal); class rule; diag-H objective. Times in seconds on this machine.", "",
          "| size | weights | brute force (s) | exact sketch (s) | certified IS (s) | blocks rounded by certified | certified? | winner | sketch agrees | certified agrees | margin to 2nd (dB) |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r[0]}x{r[0]} | {r[1]:,} | {r[2]:.3f} | {r[3]:.3f} | {r[4]:.3f} | {r[5]:,} of {r[6]:,} ({100 * r[5] / r[6]:.2f}%) | "
                  f"{'yes' if r[7] else 'no'} | {r[8]} | {'yes' if r[9] else 'NO'} | {'yes' if r[10] else 'NO'} | {r[11]:.2f} |")
    with open(os.path.join(HERE, "results", "selector_scaling.md"), "w") as f:
        f.write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
