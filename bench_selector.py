"""Accuracy vs cost of every selector in selector.APPROACHES (Aryan).

    python bench_selector.py [--n 1000] [--npz assignment_data.npz]

Truth for each matrix: quantize W with all five candidates (class rule `ocp`, and `opt` for
reference) and measure the relative Frobenius error of Y = W X on the held-out odd columns of X
(D6).  H for the "way 2" approaches comes from the even columns only.  Writes
results/selector_bench.csv (one row per matrix and approach) and results/selector_bench.md.
The learned tree is trained on a separate random set (seed 99) and never sees the test matrices.
"""
import argparse
import csv
import json
import os
import time

import numpy as np

import selector as S
import selector_suite as T
from formats import quantize, split_X

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")


def truth(W, X, policy="ocp"):
    Xf, Xe = split_X(X)
    y, w = {}, {}
    for n in S.CANDIDATES:
        D = W - quantize(W, n, policy=policy)[0]
        y[n] = float(((D @ Xe) ** 2).sum())
        w[n] = float((D ** 2).sum())
    return y, w


def regret(err, pick):
    best = min(err.values())
    return 0.0 if err[pick] <= best else 10 * np.log10(err[pick] / best)


def train_tree(n=600, seed=99):
    F, y = [], []
    for _, W, X in T.random_suite(n, seed):
        yt, _ = truth(W, X)
        F.append(S.features(W))
        y.append(min(yt, key=yt.get))
    return S.fit_tree(np.array(F), y)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=1000, help="random matrices")
    ap.add_argument("--npz", default=None)
    ap.add_argument("--tag", default="")
    a = ap.parse_args()
    t0 = time.time()
    tree = train_tree()
    with open(os.path.join(RES, "selector_tree.json"), "w") as f:
        json.dump(tree, f, indent=1, default=str)
    names = list(S.APPROACHES) + ["exhaustive_y"]
    rows = []
    suites = [("datasets", T.datasets(a.npz)), ("adversarial", T.adversarial()), ("random", T.random_suite(a.n))]
    for suite, gen in suites:
        for mname, W, X in gen:
            Xf, _ = split_X(X)
            h = (Xf ** 2).sum(1)
            y, w = truth(W, X)
            yo, _ = truth(W, X, "opt")
            ybest = min(y, key=y.get)
            sig = float(((W @ split_X(X)[1]) ** 2).sum())
            for ap_name in names:
                if ap_name == "exhaustive_y":
                    t1 = time.perf_counter()
                    sc = S.exhaustive(W, X=Xf)
                    sec = time.perf_counter() - t1
                elif ap_name == "learned_tree":
                    sc, sec = S.run(ap_name, W, h, tree=tree)
                else:
                    sc, sec = S.run(ap_name, W, h)
                pick = min(sc, key=sc.get)
                last = {"certified_h": S.certified.last, "certified_is_h": S.certified_is.last}.get(ap_name)
                extra = last[0] / last[1] if last else ""
                rows.append(dict(suite=suite, matrix=mname, approach=ap_name, pick=pick, true_y=ybest,
                                 true_w=min(w, key=w.get), true_opt=min(yo, key=yo.get),
                                 hit=int(pick == ybest), regret_y_db=regret(y, pick), regret_w_db=regret(w, pick),
                                 seconds=sec, best_y_rel=np.sqrt(y[ybest] / sig), sample_frac=extra))
        print(f"  {suite}: done ({time.time() - t0:.0f} s)")
    path = os.path.join(RES, f"selector_bench{a.tag}.csv")
    with open(path, "w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=list(rows[0]))
        wr.writeheader()
        wr.writerows(rows)
    summarize(rows, os.path.join(RES, f"selector_bench{a.tag}.md"), a.n)
    print(f"wrote {path} ({time.time() - t0:.0f} s)")


def summarize(rows, path, n):
    names = list(dict.fromkeys(r["approach"] for r in rows))
    md = ["<!-- generated by bench_selector.py; do not edit by hand -->",
          f"Selectors vs exhaustive. Truth: held-out Y error (odd X columns) under the class rule; "
          f"random suite n = {n}. Regret = 10 log10(error of the pick / best error). "
          "Time = median seconds per matrix (128x128 random, 100x100 datasets), this machine.", ""]
    for suite in dict.fromkeys(r["suite"] for r in rows):
        R = [r for r in rows if r["suite"] == suite]
        nm = len({r["matrix"] for r in R})
        md += [f"### {suite} ({nm} matrices)", "",
               "| approach | cost class | top-1 (Y) | mean regret dB | p95 | max | top-1 vs weight-error truth | median ms | what it is |",
               "|---|---|---|---|---|---|---|---|---|"]
        for a in names:
            A = [r for r in R if r["approach"] == a]
            rg = np.array([r["regret_y_db"] for r in A])
            tw = np.mean([r["pick"] == r["true_w"] for r in A])
            cls, desc = (S.APPROACHES[a][3], S.APPROACHES[a][4]) if a in S.APPROACHES else ("brute", "quantize all 5, full Y error on the fit columns")
            md.append(f"| {a} | {cls} | {100 * np.mean([r['hit'] for r in A]):.1f}% | {rg.mean():.3f} | "
                      f"{np.percentile(rg, 95):.2f} | {rg.max():.2f} | {100 * tw:.1f}% | "
                      f"{1000 * np.median([r['seconds'] for r in A]):.2f} | {desc} |")
        if suite == "random":
            md += ["", "Random suite by X family (top-1 vs held-out Y truth / mean regret dB):", "",
                   "| approach | " + " | ".join(["white", "chan_gain", "outlier_chan", "lowrank"]) + " |", "|---|---|---|---|---|"]
            for a in names:
                cells = []
                for xk in ("white", "chan_gain", "outlier_chan", "lowrank"):
                    A = [r for r in R if r["approach"] == a and r["matrix"].endswith("X=" + xk)]
                    cells.append(f"{100 * np.mean([r['hit'] for r in A]):.1f}% / {np.mean([r['regret_y_db'] for r in A]):.3f}")
                md.append(f"| {a} | " + " | ".join(cells) + " |")
            ex = [r for r in R if r["approach"] == "exhaustive_w"]
            md += ["", "Truth winners (Y, class rule): " + ", ".join(
                f"{k} {v}" for k, v in sorted(_count(r["true_y"] for r in ex).items())),
                   "Class-rule winner = opt winner in " + f"{100 * np.mean([r['true_y'] == r['true_opt'] for r in ex]):.1f}% of matrices."]
            for c in ("certified_h", "certified_is_h"):
                ce = [float(r["sample_frac"]) for r in R if r["approach"] == c]
                md.append(f"{c} read a median of {100 * np.median(ce):.0f}% of the blocks "
                          f"(mean {100 * np.mean(ce):.0f}%); the rest were never rounded.")
        md.append("")
    with open(path, "w") as f:
        f.write("\n".join(md))


def _count(it):
    out = {}
    for x in it:
        out[x] = out.get(x, 0) + 1
    return out


if __name__ == "__main__":
    main()
